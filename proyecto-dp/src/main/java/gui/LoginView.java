    private void jUsuarioTextFocusGained(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_jUsuarioTextFocusGained
        // Si el texto es igual al placeholder, lo limpia completamente
        if (jUsuarioText.getText().equals("ej. admin")) {
            jUsuarioText.setText("");
            jUsuarioText.setForeground(java.awt.Color.BLACK);
        }
    }//GEN-LAST:event_jUsuarioTextFocusGained

