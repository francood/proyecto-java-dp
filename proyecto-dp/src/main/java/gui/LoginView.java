    private void jUsuarioTextFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_jUsuarioTextFocusLost
        // Si al salir el campo está vacío, vuelve a poner el placeholder
        if (jUsuarioText.getText().trim().isEmpty()) {
            jUsuarioText.setText("ej. admin");
            jUsuarioText.setForeground(java.awt.Color.GRAY);
        }
    }//GEN-LAST:event_jUsuarioTextFocusLost

