    private void tblEmpleadosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblEmpleadosMouseClicked
        int fila = tblEmpleados.getSelectedRow();

        if (fila >= 0) {

            txtIdEmpleado.setText(
                    tblEmpleados.getValueAt(fila, 0).toString()
            );

            txtNombre.setText(
                    tblEmpleados.getValueAt(fila, 1).toString()
            );

            txtApellidos.setText(
                    tblEmpleados.getValueAt(fila, 2).toString()
            );

            txtEmail.setText(
                    tblEmpleados.getValueAt(fila, 3).toString()
            );

            txtUsuario.setText(
                    tblEmpleados.getValueAt(fila, 4).toString()
            );

            txtClave.setText(
                    tblEmpleados.getValueAt(fila, 5).toString()
            );
        }
    }//GEN-LAST:event_tblEmpleadosMouseClicked


