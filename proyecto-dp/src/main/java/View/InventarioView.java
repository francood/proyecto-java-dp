    private void inicializarVista() {
        // Configurar la tabla jTable1
        modeloInventario = new DefaultTableModel(
            new Object[][]{},
            new String[]{"Código", "Nombre", "Stock"}
        );
        jTable1.setModel(modeloInventario);
        jTable1.getColumnModel().getColumn(0).setPreferredWidth(60);
        jTable1.getColumnModel().getColumn(1).setPreferredWidth(200);
        jTable1.getColumnModel().getColumn(2).setPreferredWidth(50);

        // Cargar productos al iniciar
        cargarProductos();

        // Configurar combo de operación (Sumar / Restar)
        cbOperacion.removeAllItems();
        cbOperacion.addItem("Sumar");
        cbOperacion.addItem("Restar");
        cbOperacion.setSelectedIndex(0);

        // Cantidad inicial
        txtCantidad.setText("1");

       
    }

    private void cargarProductos() {
        try {
            listaProductosActual = productoController.listarTodos();
            mostrarProductos(listaProductosActual);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar inventario: " + e.getMessage());
        }
    }

    private void mostrarProductos(List<ProductoEntity> lista) {
        modeloInventario.setRowCount(0);
        for (ProductoEntity p : lista) {
            modeloInventario.addRow(new Object[]{
                p.getIdProducto(),
                p.getNombre(),
                p.getStock()
            });
        }
    }

    private void seleccionarProductoDeTabla() {
        int fila = jTable1.getSelectedRow();
        if (fila == -1) return;

        // Obtener el nombre del producto de la columna 1 (Nombre)
        String nombreProducto = jTable1.getValueAt(fila, 1).toString();
        // Obtener el stock actual (columna 2) para mostrarlo como referencia
        String stockActual = jTable1.getValueAt(fila, 2).toString();

        // Cargar el nombre en el campo de texto (o combo)
        txtNombreProducto.setText(nombreProducto);

    }
    
