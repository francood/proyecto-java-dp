    private void btnAplicarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAplicarActionPerformed
        try {
            String nombreProducto = txtNombreProducto.getText().trim();
            if (nombreProducto.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Seleccione un producto de la tabla");
                return;
            }

            ProductoEntity producto = productoController.buscarPorNombre(nombreProducto);
            if (producto == null) {
                JOptionPane.showMessageDialog(this, "Producto no encontrado");
                return;
            }

            int cantidad = Integer.parseInt(txtCantidad.getText().trim());
            if (cantidad <= 0) {
                JOptionPane.showMessageDialog(this, "Ingrese una cantidad mayor a 0");
                return;
            }

            String operacion = cbOperacion.getSelectedItem().toString();
            int nuevoStock = "Sumar".equals(operacion)
                    ? producto.getStock() + cantidad
                    : producto.getStock() - cantidad;

            if ("Restar".equals(operacion) && producto.getStock() < cantidad) {
                JOptionPane.showMessageDialog(this, "Stock insuficiente. Stock actual: " + producto.getStock());
                return;
            }

            productoController.actualizarStock(producto.getIdProducto(), nuevoStock);
            JOptionPane.showMessageDialog(this, "Stock actualizado: " + producto.getNombre() + "\nNuevo stock: " + nuevoStock);
            cargarProductos(); // Recargar tabla
            txtCantidad.setText("1");
            txtNombreProducto.setText("");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnAplicarActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
         String texto = txtBuscarProducto.getText().trim().toLowerCase();
        if (texto.isEmpty()) {
            cargarProductos();
            return;
        }
        try {
            // Filtrar la lista completa por nombre
            List<ProductoEntity> filtrados = productoController.listarTodos();
            filtrados.removeIf(p -> !p.getNombre().toLowerCase().contains(texto));
            mostrarProductos(filtrados);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al filtrar: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

